    private void btnApproveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnApproveActionPerformed
        // TODO add your handling code here:

        int row = jTable1.getSelectedRow();
        if (row < 0) {
            JOptionPane.showMessageDialog(this, "Pilih reservasi dulu");
            return;
        }
        int id = (Integer) jTable1.getValueAt(row, 0);
        ReservasiDAO dao = new ReservasiDAO();
        dao.updateStatus(id, "Dikonfirmasi");
        
        loadPendingRooms();
    }//GEN-LAST:event_btnApproveActionPerformed

    private void btnRejectActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRejectActionPerformed
        // TODO add your handling code here:
    int row = jTable1.getSelectedRow();
    if (row < 0) {
        JOptionPane.showMessageDialog(this, "Pilih reservasi dulu");
        return;
    }

    int id = (Integer) jTable1.getValueAt(row, 0);
    ReservasiDAO dao = new ReservasiDAO();
    dao.updateStatus(id, "Dibatalkan");

    JOptionPane.showMessageDialog(this, "Reservasi ditolak");
    loadPendingRooms();
    }//GEN-LAST:event_btnRejectActionPerformed

