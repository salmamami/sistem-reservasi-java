    private void loadDataPelanggan(String keyword) {
        model.setColumnCount(0);
        model.setRowCount(0);
        model.addColumn("ID");
        model.addColumn("Nama");
        model.addColumn("No HP");
        model.addColumn("Email");

    try {
        PelangganDAO dao = new PelangganDAO();
        List<Pelanggan> list = dao.search(keyword);

        for (Pelanggan p : list) {
            Object[] row = {
                p.getIdPelanggan(),
                p.getNama(),
                p.getNoHp(),
                p.getEmail()
            };
            model.addRow(row);
        }
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, e.getMessage());
    }
    }


    private void loadDataReservasi() {
        model.setColumnCount(0);
        model.setRowCount(0);
        model.addColumn("ID Reservasi");
        model.addColumn("Nama Pelanggan");
        model.addColumn("Tanggal");
        model.addColumn("Status");
        
        ReservasiDAO dao = new ReservasiDAO();
        List<Reservasi> list = dao.getAllWithNamaPelanggan();

    for (Reservasi r : list) {
        Object[] row = {
            r.getIdReservasi(),
            r.getNamaPelanggan(),
            r.getTanggal(),
            r.getStatus()
        };
        model.addRow(row);
    }
}
    
    private void loadPendingRooms() {
        model.setColumnCount(0);
        model.setRowCount(0);
        
        model.addColumn("ID Res");
        model.addColumn("ID Room");
        model.addColumn("Tanggal");
        model.addColumn("Lama");
        model.addColumn("Total");
        model.addColumn("Status");
        
        ReservasiDAO dao = new ReservasiDAO();
        List<Reservasi> list = dao.getPendingRooms();
        
        for (Reservasi r : list) {
            Object[] row = {
                r.getIdReservasi(),
                r.getIdRoom(),
                r.getTanggal(),
                r.getLamaMenginap(),
                r.getTotalHarga(),
                r.getStatus()
            };
            model.addRow(row);
        }
    }


