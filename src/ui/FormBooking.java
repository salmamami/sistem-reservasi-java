    private void btnSimpanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSimpanActionPerformed
        // TODO add your handling code here:
        try {
            
            if (txtNama.getText().trim().isEmpty() ||
                    txtCheckin.getText().trim().isEmpty() ||
                    txtLama.getText().trim().isEmpty()) {
                
                JOptionPane.showMessageDialog(this, "Semua field wajib diisi");
                return;
            }
            
            if (selectedRoomId == null) {
                JOptionPane.showMessageDialog(this, "Pilih kamar terlebih dahulu");
                return;
            }
            
            int lama;
            try {
                lama = Integer.parseInt(txtLama.getText().trim());
            } catch (NumberFormatException ex) {
                JOptionPane.showMessageDialog(this, "Lama menginap harus angka");
                return;
            }
            
            if (lama <= 0) {
                JOptionPane.showMessageDialog(this, "Lama menginap harus > 0");
                return;
            }
            DateTimeFormatter formatter = DateTimeFormatter.ofPattern("yyyy-MM-dd");
            LocalDate tgl;
            
            try {
                tgl = LocalDate.parse(txtCheckin.getText().trim(), formatter);
            } catch (DateTimeParseException e) {
                JOptionPane.showMessageDialog(this, "Format tanggal harus yyyy-MM-dd");
                return;
            }
            
            BigDecimal total = selectedRoomPrice.multiply(BigDecimal.valueOf(lama));
            
            if (pelanggan == null) {
                PelangganDAO pDao = new PelangganDAO();
                pelanggan = pDao.getByUserId(currentUser.getIdUser());
                if (pelanggan == null) {
                    JOptionPane.showMessageDialog(this, "Data pelanggan tidak ditemukan. Lengkapi data di menu pelanggan dulu.");
                    return;
                }
            }

        
        Reservasi r = new Reservasi();
        r.setIdPelanggan(pelanggan.getIdPelanggan());
        r.setIdUser(currentUser.getIdUser());
        r.setIdRoom(selectedRoomId);
        r.setTanggal(Date.valueOf(tgl));
        r.setLamaMenginap(lama);
        r.setTotalHarga(total);
        r.setStatus("Menunggu");  // pending

        ReservasiDAO dao = new ReservasiDAO();
        dao.insertBooking(r);

        JOptionPane.showMessageDialog(this, "Booking berhasil disimpan, menunggu konfirmasi admin");

        new FormPelanggan(currentUser).setVisible(true);
        dispose();

    } catch (Exception e) {
        
        JOptionPane.showMessageDialog(this, "Terjadi kesalahan: " + e.getMessage());
    }
    
    }//GEN-LAST:event_btnSimpanActionPerformed

