    private void loadKamarKosong() {
        try {
            DefaultTableModel model = (DefaultTableModel) tblKamarKosong.getModel();
            model.setRowCount(0);
            for (Room r : roomDAO.getKamarKosong()) {
                model.addRow(new Object[]{
                    r.getId(),
                    r.getNomorKamar(),
                    r.getTipe(),
                    r.getHarga(),
                    r.getStatus()
                });
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Gagal load kamar: " + e.getMessage());
        }
    }

    private void setupListeners() {
        tblKamarKosong.getSelectionModel().addListSelectionListener(e -> {
            if (!e.getValueIsAdjusting() && tblKamarKosong.getSelectedRow() >= 0) {
                int row = tblKamarKosong.getSelectedRow();
                
                Object idObj = tblKamarKosong.getValueAt(row, 0);
                selectedRoomId = (idObj instanceof Integer)
                        ? (Integer) idObj
                        : Integer.parseInt(idObj.toString());
                Object hargaObj = tblKamarKosong.getValueAt(row, 3);
                double hargaDouble = (hargaObj instanceof Double)
                        ? (Double) hargaObj
                        : Double.parseDouble(hargaObj.toString());
                
                selectedRoomPrice = BigDecimal.valueOf(hargaDouble);
                txtHarga.setText(String.valueOf(hargaDouble));
                hitungTotalOtomatis();
            }
        });
        
        txtLama.getDocument().addDocumentListener(new javax.swing.event.DocumentListener() {
            public void insertUpdate(javax.swing.event.DocumentEvent e) { hitungTotalOtomatis(); }
            public void removeUpdate(javax.swing.event.DocumentEvent e) { hitungTotalOtomatis(); }
            public void changedUpdate(javax.swing.event.DocumentEvent e) { hitungTotalOtomatis(); }
        });
    }

    private void hitungTotalOtomatis() {
        try {
            double harga = Double.parseDouble(txtHarga.getText());
            int lama = Integer.parseInt(txtLama.getText());
            double total = harga * lama;
            txtTotal.setText(String.valueOf(total));
        } catch (NumberFormatException ex) {
            txtTotal.setText("");
        }
    }

