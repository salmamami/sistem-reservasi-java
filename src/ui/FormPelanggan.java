    private void hapusActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_hapusActionPerformed
        // TODO add your handling code here:
        int konfirmasi = JOptionPane.showConfirmDialog(
            this,
            "Yakin ingin menghapus data pelanggan?",
            "Konfirmasi",
            JOptionPane.YES_NO_OPTION
        );

        if (konfirmasi == JOptionPane.YES_OPTION) {
            PelangganDAO dao = new PelangganDAO();
            dao.deleteByUserId(userLogin.getIdUser());
            
            // Kosongkan form
            namapelanggan.setText("");
            nohp.setText("");
            email.setText("");
            
            namapelanggan.setEnabled(true);
            nohp.setEnabled(true);
            email.setEnabled(true);
            
            JOptionPane.showMessageDialog(this, "Data pelanggan berhasil dihapus");
        }
    }//GEN-LAST:event_hapusActionPerformed

    private void simpanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_simpanActionPerformed
        // TODO add your handling code here:
        if (!modeEdit) {
            JOptionPane.showMessageDialog(this,
                "Klik Ubah Data terlebih dahulu");
            return;
        }
        
        if (namapelanggan.getText().isEmpty() ||
            nohp.getText().isEmpty() ||
            email.getText().isEmpty()) {

            JOptionPane.showMessageDialog(this,
                "Nama, No HP, dan Email wajib diisi");
            return;
        }
        
        PelangganDAO dao = new PelangganDAO();
        Pelanggan p = dao.getByUserId(userLogin.getIdUser());
        
        Pelanggan data = new Pelanggan();
        data.setNama(namapelanggan.getText());
        data.setNoHp(nohp.getText());
        data.setEmail(email.getText());
        data.setIdUser(userLogin.getIdUser());
        
        if (p == null) {
            // === USER BARU ===
            dao.insert(data);
            JOptionPane.showMessageDialog(this,
                "Data pelanggan berhasil disimpan");
        } else {
            // === USER LAMA ===
            dao.update(data);
            JOptionPane.showMessageDialog(this,
                "Data pelanggan berhasil diperbarui");
        }
   
        namapelanggan.setEnabled(false);
        nohp.setEnabled(false);
        email.setEnabled(false);

        modeEdit = false;
    }//GEN-LAST:event_simpanActionPerformed

