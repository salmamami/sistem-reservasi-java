    private void loadDataPelanggan() {
        PelangganDAO dao = new PelangganDAO();
        Pelanggan p = dao.getByUserId(userLogin.getIdUser());
        
        if (p != null) {
            //Data sudah ada
            namapelanggan.setText(p.getNama());
            nohp.setText(p.getNoHp());
            email.setText(p.getEmail());
            
            namapelanggan.setEnabled(false);
            nohp.setEnabled(false);
            email.setEnabled(false);
            
            modeEdit = false;
        } else {
            //User baru (blm ada data)
            namapelanggan.setEnabled(true);
            nohp.setEnabled(true);
            email.setEnabled(true);
            
            modeEdit = true;
             
            JOptionPane.showMessageDialog(
                this,
                "Silakan lengkapi data diri terlebih dahulu"
            );    
        }
    }
    
    private void loadRiwayatReservasi() {
        ReservasiDAO dao = new ReservasiDAO();
        List<Reservasi> list = dao.getByUser(userLogin.getIdUser());
        
        DefaultTableModel model = (DefaultTableModel) jTable3.getModel();
        model.setRowCount(0);
        
        if (list == null || list.isEmpty()) {
            return;
        }
        
        for (Reservasi r : list) {
            model.addRow(new Object[]{
                r.getIdReservasi(),
                r.getTanggal(),        // Tanggal (check-in)
                r.getLamaMenginap(),   // Lama Menginap
                r.getTotalHarga(),     // Total Harga
                r.getStatus()          // Status (Menunggu / Dikonfirmasi / Dibatalkan)

            });
        }
    }
    
